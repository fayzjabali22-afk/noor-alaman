/**
 * Match user prompt against knowledge base
 */
export function findMatchingFaqAnswer(prompt: string): string | null {
  const normalized = prompt.trim().toLowerCase();

  for (const item of NOOR_ASSISTANT_KNOWLEDGE_BASE) {
    if (normalized.includes(item.question.toLowerCase())) {
      return item.answer;
    }
    const matchCount = item.keywords.filter((kw) => normalized.includes(kw.toLowerCase())).length;
    if (matchCount >= 2) {
      return item.answer;
    }
  }

  return null;
}
